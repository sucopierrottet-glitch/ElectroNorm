  /// Find a raceway profile by type and trade size
  static RacewayProfile? findProfile(RacewayType type, String tradeSize) {
    try {
      return profiles.firstWhere(
        (p) => p.type == type && p.tradeSize == tradeSize,
      );
    } catch (_) {
      return null;
    }
  }

  /// Get a raceway profile, throwing ArgumentError if not found
  static RacewayProfile getProfile(RacewayType type, String tradeSize) {
    final profile = findProfile(type, tradeSize);
    if (profile == null) {
      throw ArgumentError(
        'Raceway profile not found for type: ${type.name}, tradeSize: $tradeSize',
      );
    }
    return profile;
  }

  /// Get all profiles for a given raceway type
  static List<RacewayProfile> getProfilesForType(RacewayType type) {
    return profiles.where((p) => p.type == type).toList();
  }

  /// Get profiles larger than the current trade size (for upsize recommendations)
  static List<RacewayProfile> getUpsizeProfiles(
    RacewayType type,
    String currentTradeSize,
  ) {
    final currentIndex = standardTradeSizes.indexOf(currentTradeSize);
    if (currentIndex == -1 || currentIndex >= standardTradeSizes.length - 1) {
      return [];
    }

    final largerSizes = standardTradeSizes.sublist(currentIndex + 1);
    return largerSizes
        .map((s) => findProfile(type, s))
        .whereType<RacewayProfile>()
        .toList();
  }
